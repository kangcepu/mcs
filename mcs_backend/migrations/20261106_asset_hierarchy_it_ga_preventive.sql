-- Asset hierarchy and preventive checklist support for IT / GA.
-- Run once against the MCS MySQL/MariaDB database before deploying the code.

ALTER TABLE asset
  ADD COLUMN parent_asset_id INT NULL AFTER AssetID,
  ADD INDEX idx_asset_parent (parent_asset_id);

CREATE TABLE tb_wo_it_detail (
  id INT NOT NULL AUTO_INCREMENT,
  wo_number VARCHAR(120) NOT NULL,
  schedule_detail_id INT DEFAULT NULL,
  generated_date DATE DEFAULT NULL,
  asset_id VARCHAR(50) DEFAULT NULL,
  asset_code VARCHAR(80) DEFAULT NULL,
  id_division INT DEFAULT NULL,
  shift VARCHAR(50) DEFAULT NULL,
  type_wo VARCHAR(60) DEFAULT NULL,
  job_title VARCHAR(255) NOT NULL,
  part_mesin VARCHAR(255) DEFAULT NULL,
  job_requirement TEXT DEFAULT NULL,
  running_hours VARCHAR(80) DEFAULT NULL,
  type_schedule VARCHAR(60) DEFAULT NULL,
  choose_day VARCHAR(30) DEFAULT NULL,
  executor VARCHAR(255) DEFAULT NULL,
  start_date DATE DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT NULL,
  maintenance_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  request_qty DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  request_part VARCHAR(255) DEFAULT NULL,
  request_uom VARCHAR(30) DEFAULT NULL,
  keterangan TEXT DEFAULT NULL,
  done_at DATETIME DEFAULT NULL,
  done_by VARCHAR(120) DEFAULT NULL,
  need_request_part TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_wo_it_schedule_day (schedule_detail_id, generated_date),
  KEY idx_wo_it_detail_wo (wo_number),
  KEY idx_wo_it_detail_asset (asset_code),
  KEY idx_wo_it_detail_schedule (schedule_detail_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

